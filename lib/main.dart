import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';
import 'package:provider/provider.dart';

import 'data/activity_store.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'providers/auth_provider.dart';
import 'providers/content_provider.dart';
import 'providers/tab_navigator.dart';
import 'screens/auth_gate.dart';
import 'services/auth_service.dart';
import 'theme/app_theme.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(
    MultiProvider(
      providers: [
        ChangeNotifierProvider(create: (_) => AuthProvider(AuthService())),
        // ContentProvider follows the logged-in user: it loads their saved
        // activity on log in and clears it on log out.
        ChangeNotifierProxyProvider<AuthProvider, ContentProvider>(
          create: (_) => ContentProvider(store: FirestoreActivityStore()),
          update: (_, auth, content) =>
              content!..attachUser(auth.user?.uid, authorNameFor(auth)),
        ),
        ChangeNotifierProvider(create: (_) => TabNavigator()),
      ],
      child: const LocalLegendsApp(),
    ),
  );
}

/// The name shown on stories you post: your display name, else @username.
String authorNameFor(AuthProvider auth) {
  final name = auth.user?.displayName?.trim();
  if (name != null && name.isNotEmpty) return name;
  final username = auth.username;
  return username == null ? 'Explorer' : '@$username';
}

class LocalLegendsApp extends StatelessWidget {
  const LocalLegendsApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'LocalLegends',
      debugShowCheckedModeBanner: false,
      theme: buildAppTheme(),
      home: const AuthGate(),
    );
  }
}
